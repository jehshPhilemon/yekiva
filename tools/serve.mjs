#!/usr/bin/env node
// Sert l'app dans un navigateur (Termux/dev), SANS proxy et SANS serveur local.
// L'app appelle l'API Yekiva TTS DIRECTEMENT (même code que dans l'APK) :
//   node tools/serve.mjs [port] [--api https://api.jehshphilemon.com] [--key YKV-....]
// --api/--key : bakés pour cette session (défaut : TTS_API_URL / TTS_API_KEY env).
// Sans --api : mode offline (cache + voix téléphone), pareil que l'APK offline.
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { extname, join, normalize, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../app/www", import.meta.url)));
const args = process.argv.slice(2);
const port = Number(args.find((a) => !a.startsWith("--")) ?? 8080);
const flag = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? null : (args[i + 1] ?? "");
};
const api = (flag("--api") ?? process.env.TTS_API_URL ?? process.env.YEKIVA_SERVER_URL ?? "").trim();
const key = (flag("--key") ?? flag("--token") ?? process.env.TTS_API_KEY ?? process.env.APP_TOKEN ?? "").trim();

const TYPES = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8", ".json": "application/json; charset=utf-8", ".svg": "image/svg+xml",
  ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".mp3": "audio/mpeg", ".ogg": "audio/ogg", ".wav": "audio/wav",
};

createServer(async (req, res) => {
  try {
    const path = decodeURIComponent(new URL(req.url, "http://x").pathname);
    const full = path.endsWith("/") ? `${path}index.html` : path;
    // Dev-only: injecte l'API dans config.js pour cette session (prod = build-config.mjs).
    if (full === "/js/config.js") {
      const body =
        `// GENERATED by tools/serve.mjs (dev only) — prod uses tools/build-config.mjs.\n` +
        `export const config = {\n  apiUrl: ${JSON.stringify(api)},\n  apiKey: ${JSON.stringify(key)},\n};\n`;
      res.writeHead(200, { "content-type": "text/javascript; charset=utf-8", "cache-control": "no-store" });
      res.end(body);
      return;
    }
    const file = join(root, normalize(full));
    if (file !== root && !file.startsWith(root + sep)) throw Object.assign(new Error("forbidden"), { code: 403 });
    const body = await readFile(file);
    res.writeHead(200, { "content-type": TYPES[extname(file)] ?? "application/octet-stream", "cache-control": "no-store" });
    res.end(body);
  } catch (e) {
    res.writeHead(e.code === 403 ? 403 : 404);
    res.end("not found");
  }
}).listen(port, () => console.log(`Yekiva at http://localhost:${port}  (api: ${api || "(offline — cache + voix téléphone)"})`));
