#!/usr/bin/env node
// Minimal static server to try the app in a browser, no Android SDK needed. Zero dependencies.
//   node tools/serve.mjs [port] [--api https://...]   then open  http://localhost:8080  in a browser
// "localhost" is a secure context: the microphone (getUserMedia) works there without HTTPS.
// --api bakes the Yekiva server URL into the app for this session (default: http://localhost:8787
// when the Yekiva server runs locally, else offline placeholders). The learner never types a URL.
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { extname, join, normalize, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("../app/www", import.meta.url)));
const args = process.argv.slice(2);
const port = Number(args.find((a) => !a.startsWith("--")) ?? 8080);
const flag = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? null : (args[i + 1] ?? "");
};
const api = flag("--api") ?? "http://localhost:8787";

const TYPES = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".mjs": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8", ".json": "application/json; charset=utf-8", ".svg": "image/svg+xml",
  ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".mp3": "audio/mpeg", ".ogg": "audio/ogg", ".wav": "audio/wav",
};

createServer(async (req, res) => {
  try {
    let path = decodeURIComponent(new URL(req.url, "http://x").pathname);
    if (path.endsWith("/")) path += "index.html";
    // Dev-only injection: config.js placeholders -> SAME ORIGIN (this server).
    // Same-origin = no CORS, no wrong-port mistakes: /v1/* below is proxied to the
    // real Yekiva server (--api, default http://localhost:8787).
    if (path === "/js/config.js") {
      const origin = `http://localhost:${port}`;
      const body =
        `// GENERATED by tools/serve.mjs (dev only) — prod uses tools/build-config.mjs.\n` +
        `export const config = {\n  serverUrl: ${JSON.stringify(origin)},\n  appToken: "",\n};\n`;
      res.writeHead(200, { "content-type": "text/javascript; charset=utf-8", "cache-control": "no-store" });
      res.end(body);
      return;
    }
    // Dev-only proxy: /v1/* and /health -> the Yekiva server. If the Yekiva server
    // is down, answer 502 with a clear message instead of a confusing 404.
    if (path === "/health" || path.startsWith("/v1/")) {
      try {
        const target = new URL(path + (new URL(req.url, "http://x").search ?? ""), api);
        const chunks = [];
        await new Promise((resolve, reject) => {
          req.on("data", (c) => chunks.push(c));
          req.on("end", resolve);
          req.on("error", reject);
        });
        const upstream = await fetch(target, {
          method: req.method,
          headers: { "content-type": req.headers["content-type"] ?? "application/octet-stream" },
          body: ["GET", "HEAD"].includes(req.method) ? undefined : Buffer.concat(chunks),
        });
        const buf = Buffer.from(await upstream.arrayBuffer());
        res.writeHead(upstream.status, {
          "content-type": upstream.headers.get("content-type") ?? "application/octet-stream",
          "cache-control": "no-store",
        });
        res.end(buf);
      } catch {
        res.writeHead(502, { "content-type": "application/json" });
        res.end(JSON.stringify({ error: `serveur Yekiva injoignable (${api}) : lancez 'cd server && node --env-file=.env src/index.js'` }));
      }
      return;
    }
    const file = join(root, normalize(path));
    if (file !== root && !file.startsWith(root + sep)) throw Object.assign(new Error("forbidden"), { code: 403 });
    const body = await readFile(file);
    res.writeHead(200, { "content-type": TYPES[extname(file)] ?? "application/octet-stream", "cache-control": "no-store" });
    res.end(body);
  } catch (e) {
    res.writeHead(e.code === 403 ? 403 : 404);
    res.end("not found");
  }
}).listen(port, () => console.log(`Yekiva at http://localhost:${port}  (Ctrl+C to stop)  [api: ${api}]`));
